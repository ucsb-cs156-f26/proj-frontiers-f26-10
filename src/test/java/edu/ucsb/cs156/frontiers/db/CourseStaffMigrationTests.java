package edu.ucsb.cs156.frontiers.db;

import static org.junit.jupiter.api.Assertions.*;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.util.UUID;
import liquibase.Liquibase;
import liquibase.database.jvm.JdbcConnection;
import liquibase.exception.LiquibaseException;
import liquibase.resource.ClassLoaderResourceAccessor;
import org.junit.jupiter.api.Test;

class CourseStaffMigrationTests {
  private static final String MIGRATION = "db/migration/changes/030-course-staff-unique-email.json";

  private Connection staffDatabase() throws SQLException {
    Connection connection = DriverManager.getConnection("jdbc:h2:mem:" + UUID.randomUUID());
    try (var statement = connection.createStatement()) {
      statement.execute(
          "CREATE TABLE COURSE_STAFF (ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, COURSE_ID BIGINT NOT NULL, EMAIL VARCHAR(255))");
    }
    return connection;
  }

  @Test
  void migration_rejects_same_course_duplicate_but_allows_email_in_another_course()
      throws Exception {
    try (Connection connection = staffDatabase();
        Liquibase liquibase =
            new Liquibase(
                MIGRATION, new ClassLoaderResourceAccessor(), new JdbcConnection(connection))) {
      liquibase.update("");
      try (var statement = connection.createStatement()) {
        statement.executeUpdate(
            "INSERT INTO COURSE_STAFF (COURSE_ID, EMAIL) VALUES (1, 'alice@example.org')");
        SQLException duplicate =
            assertThrows(
                SQLException.class,
                () ->
                    statement.executeUpdate(
                        "INSERT INTO COURSE_STAFF (COURSE_ID, EMAIL) VALUES (1, 'alice@example.org')"));
        assertEquals("23505", duplicate.getSQLState());
        statement.executeUpdate(
            "INSERT INTO COURSE_STAFF (COURSE_ID, EMAIL) VALUES (2, 'alice@example.org')");
        try (var rows = statement.executeQuery("SELECT COUNT(*) FROM COURSE_STAFF")) {
          assertTrue(rows.next());
          assertEquals(2, rows.getInt(1));
        }
      }
    }
  }

  @Test
  void migration_stops_without_deleting_existing_duplicate_staff() throws Exception {
    try (Connection connection = staffDatabase();
        Liquibase liquibase =
            new Liquibase(
                MIGRATION, new ClassLoaderResourceAccessor(), new JdbcConnection(connection));
        var statement = connection.createStatement()) {
      statement.executeUpdate(
          "INSERT INTO COURSE_STAFF (COURSE_ID, EMAIL) VALUES (1, 'alice@example.org'), (1, 'alice@example.org')");
      assertThrows(LiquibaseException.class, () -> liquibase.update(""));
      try (var rows = statement.executeQuery("SELECT COUNT(*) FROM COURSE_STAFF")) {
        assertTrue(rows.next());
        assertEquals(2, rows.getInt(1));
      }
    }
  }
}
